// Writes docs/appellation_grapes_fill.sql from aocgrapes.js (the grapes an appellation's own rules name), for the owner to run by hand in the
// Supabase SQL editor. Run:  node docs/appellation_grapes.mjs   (reads the public place and grape lists with the public key in config.js).
// Only lines marked checked: true with rule "only" or "main" are written; a line still to check is listed in the file's header, commented out;
// a "usual" line (white Burgundy: Chardonnay, Pinot Blanc also allowed) is shown on cards but never stored.
// The SQL adds a grape row (basis 'rule') only to a wine in that appellation, of that type, that has no grape row of any kind yet, and logs every
// row it adds in rule_grape_fill_log, so the fill can be undone (the undo statement is at the end of the file, commented out).
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { APPELLATION_GRAPES } from "../aocgrapes.js";
import { matchKey, plainKey } from "../text.js";
import { SUPABASE_URL, SUPABASE_KEY } from "../config.js";

async function all(path) {
  const rows = [];
  for (let from = 0; ; from += 1000) {
    const r = await fetch(`${SUPABASE_URL}/rest/v1/${path}`, { headers: { apikey: SUPABASE_KEY, Authorization: `Bearer ${SUPABASE_KEY}`, Range: `${from}-${from + 999}` } });
    if (!r.ok) throw new Error(`${path}: ${r.status}`);
    const j = await r.json(); rows.push(...j); if (j.length < 1000) break;
  }
  return rows;
}
const [areas, grapes] = await Promise.all([all("geo_areas?select=id,name,level,parent_id"), all("grapes?select=id,name")]);
const byId = new Map(areas.map((g) => [g.id, g]));
const countryOf = (g) => { for (let x = g, i = 0; x && i < 6; x = byId.get(x.parent_id), i++) if (x.level === "country") return x.name; return ""; };
const grapeId = new Map(grapes.map((g) => [plainKey(g.name), g.id]));
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

const values = [], skipped = [], toCheck = [];
for (const line of APPELLATION_GRAPES) {
  if (!line.checked) { toCheck.push(line); continue; }
  if (line.rule === "usual") continue;   // shown on cards, never stored: the rules allow another grape beside it (aocgrapes.js)
  const places = areas.filter((g) => g.level === "appellation" && matchKey(g.name) === matchKey(line.appellation) && plainKey(countryOf(g)) === plainKey(line.country));
  const gid = grapeId.get(plainKey(line.grape));
  if (!places.length || !gid) { skipped.push(`${line.appellation} (${line.style}): ${!places.length ? "no such appellation in our place list" : "grape not in our grape list"}`); continue; }
  for (const p of places) values.push(`  (${q(p.id)}::uuid, ${q(line.style)}, ${q(gid)}::uuid, ${q(line.appellation)}, ${q(line.rule)}, ${q(line.source)})`);
}

const sql = `-- GRAPES FROM THE APPELLATION'S OWN RULES (owner, 2026-10-17; all versions). GENERATED by docs/appellation_grapes.mjs on ${new Date().toISOString().slice(0, 10)}
-- from aocgrapes.js: do not edit by hand. Run once in the Supabase SQL editor (New query, paste all, Run). Safe to run again: it only fills wines
-- that still have no grape row at all, and only from lines whose official text was read (checked).
-- A wine of that type in that appellation gets the grape with basis 'rule' (the card shows it in the "from a rule" style). Label and editor grapes
-- are never touched. Every row added is logged in rule_grape_fill_log; the undo statement is at the end, commented out.
${skipped.length ? "-- Lines left out because they do not match our lists:\n" + skipped.map((x) => "--   " + x).join("\n") + "\n" : ""}-- Lines still to check (not filled until an editor has read the official text and marked them checked in aocgrapes.js):
${toCheck.map((l) => `--   ${l.appellation} (${l.style}): ${l.grape}`).join("\n")}

create table if not exists public.rule_grape_fill_log (
  wine_id uuid not null, grape_id uuid not null, appellation text, rule text, source text, filled_at timestamptz not null default now(),
  primary key (wine_id, grape_id)
);
alter table public.rule_grape_fill_log enable row level security;   -- owner's record only: no policy, so only the SQL editor reads it

with rules (appellation_id, style, grape_id, appellation, rule, source) as (values
${values.join(",\n")}
), targets as (
  select w.id as wine_id, r.grape_id, r.appellation, r.rule, r.source
  from public.wines w join rules r on r.appellation_id = w.appellation_id and w.style::text = r.style
  where not exists (select 1 from public.wine_grapes wg where wg.wine_id = w.id)
), added as (
  insert into public.wine_grapes (wine_id, grape_id, basis, position)
  select wine_id, grape_id, 'rule', 1 from targets
  on conflict do nothing
  returning wine_id, grape_id
)
insert into public.rule_grape_fill_log (wine_id, grape_id, appellation, rule, source)
select a.wine_id, a.grape_id, t.appellation, t.rule, t.source from added a join targets t using (wine_id, grape_id)
on conflict do nothing;

-- Check: the wines that now carry a grape from their appellation's rules, by appellation.
select appellation, count(*) as wines from public.rule_grape_fill_log group by appellation order by wines desc;

-- UNDO (only if the owner wants these rule grapes taken off again):
-- delete from public.wine_grapes wg using public.rule_grape_fill_log l where wg.wine_id = l.wine_id and wg.grape_id = l.grape_id and wg.basis = 'rule';
-- delete from public.rule_grape_fill_log;
`;
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), "appellation_grapes_fill.sql"), sql);
console.log(`appellation_grapes_fill.sql: ${values.length} appellation lines; ${toCheck.length} to check; ${skipped.length} left out`);
if (skipped.length) console.log(skipped.join("\n"));
